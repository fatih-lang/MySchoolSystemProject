// Wait until the Django Admin page has finished loading.
document.addEventListener("DOMContentLoaded", function () {

    // Find the Academic Structure dropdown.
    const academicStructureField =
        document.getElementById(
            "id_academic_structure"
        );

    // Find the School Types multiple-select field.
    const schoolTypesField =
        document.getElementById(
            "id_school_types"
        );

    // Find the hidden compatibility field.
    const compatibilityField =
        document.getElementById(
            "id_school_type_compatibility"
        );

    // Stop if any required field cannot be found.
    if (
        !academicStructureField ||
        !schoolTypesField ||
        !compatibilityField
    ) {
        return;
    }

    // Read the compatibility map generated by Django.
    const schoolTypeChoices =
        JSON.parse(
            compatibilityField.value || "{}"
        );

    // Rebuild the School Types choices
    // whenever the Academic Structure changes.
    function updateSchoolTypes() {

        const selectedStructure =
            academicStructureField.value;

        // Remove the current choices.
        schoolTypesField.innerHTML = "";

        // Get the School Types allowed for
        // the selected Academic Structure.
        const choices =
            schoolTypeChoices[selectedStructure] || [];

        // Add each compatible School Type.
        choices.forEach(function (choice) {

            const option =
                document.createElement("option");

            option.value = choice[0];
            option.textContent = choice[1];

            schoolTypesField.appendChild(option);
        });
    }

    // Update School Types whenever
    // Academic Structure changes.
    academicStructureField.addEventListener(
        "change",
        updateSchoolTypes
    );

    // Do not call updateSchoolTypes() here.
    //
    // This keeps School Types empty when
    // creating a new School until an
    // Academic Structure is selected.
});